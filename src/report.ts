import {
  basename,
  humanBitrate,
  humanBytes,
  humanDuration,
  streamRows,
  type FfprobeData,
  type Stream,
} from "./ffprobe";
import { detectWarnings } from "./warnings";
import type { T } from "./i18n";

function esc(s: string): string {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
}

/** ストリームの全フィールドを [key, value] 配列に。 */
function allFields(s: Stream): [string, string][] {
  return Object.entries(s as unknown as Record<string, unknown>).map(([k, v]) => [
    k,
    v !== null && typeof v === "object" ? JSON.stringify(v) : String(v),
  ]);
}

// ===================== HTML =====================
export function buildHtmlReport(data: FfprobeData, path: string, t: T): string {
  const f = data.format;
  const streams = data.streams ?? [];
  const warnings = detectWarnings(data, t);

  const summary: [string, string][] = [
    [t("ファイル", "File"), basename(path)],
    [t("フォーマット", "Format"), f?.format_long_name ?? f?.format_name ?? "—"],
    [t("再生時間", "Duration"), humanDuration(f?.duration)],
    [t("サイズ", "Size"), humanBytes(f?.size)],
    [t("総ビットレート", "Total bitrate"), humanBitrate(f?.bit_rate)],
    [t("ストリーム数", "Streams"), String(f?.nb_streams ?? streams.length)],
  ];
  const rows = (arr: [string, string][]) =>
    arr.map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v)}</td></tr>`).join("");

  const streamsHtml = streams
    .map((s) => {
      const curated = rows(streamRows(s, t));
      const all = rows(allFields(s));
      return `<div class="stream"><h3>#${s.index} ${esc(s.codec_type ?? "")} — ${esc(
        s.codec_name ?? ""
      )}</h3><table>${curated}</table>
      <details><summary>${esc(t("全フィールド", "All fields"))}</summary><table>${all}</table></details></div>`;
    })
    .join("");

  const metaHtml =
    f?.tags && Object.keys(f.tags).length
      ? `<h2>${esc(t("メタデータ", "Metadata"))}</h2><table>${rows(
          Object.entries(f.tags).map(([k, v]) => [k, String(v)])
        )}</table>`
      : "";

  const warningsHtml = warnings.length
    ? `<h2>${esc(t("警告", "Warnings"))}</h2>` +
      warnings
        .map(
          (w) =>
            `<div class="warn warn-${w.level}"><strong>${esc(w.title)}</strong><br>${esc(
              w.detail
            )}</div>`
        )
        .join("")
    : "";

  return `<!doctype html>
<html lang="ja"><head><meta charset="utf-8">
<title>ffScope report — ${esc(basename(path))}</title>
<style>
  body{font-family:-apple-system,"Segoe UI","Noto Sans JP",sans-serif;max-width:900px;margin:24px auto;padding:0 20px;color:#1c2129;background:#fff}
  h1{font-size:22px} h2{font-size:16px;margin-top:28px;border-bottom:1px solid #ddd;padding-bottom:6px}
  h3{font-size:14px;margin:14px 0 6px}
  table{border-collapse:collapse;width:100%;font-size:13px;margin-bottom:8px}
  th{text-align:left;color:#687385;font-weight:500;width:200px;padding:4px 12px 4px 0;vertical-align:top;word-break:break-all}
  td{padding:4px 0;word-break:break-all}
  .stream{border:1px solid #e2e5ea;border-radius:8px;padding:10px 14px;margin-bottom:10px}
  details{margin-top:6px} summary{cursor:pointer;color:#2f6fed;font-size:12px}
  .warn{border:1px solid #e2e5ea;border-left:3px solid #b35309;border-radius:6px;padding:8px 12px;margin:6px 0;font-size:13px}
  .warn-warning{border-left-color:#cf222e}
  .path{color:#687385;font-size:12px;word-break:break-all}
  footer{margin-top:32px;color:#8b93a3;font-size:12px}
</style></head>
<body>
<h1>ffScope — ${esc(t("解析レポート", "Analysis report"))}</h1>
<div class="path">${esc(path)}</div>
<h2>${esc(t("概要", "Summary"))}</h2>
<table>${rows(summary)}</table>
${warningsHtml}
<h2>${esc(t("ストリーム", "Streams"))}</h2>
${streamsHtml}
${metaHtml}
<footer>Generated by ffScope</footer>
</body></html>`;
}

// ===================== PDF =====================
// 注: jsPDF の標準フォントは日本語非対応のため、ラベルは英語で出力する。
export async function buildPdf(data: FfprobeData, path: string): Promise<Uint8Array> {
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import("jspdf"), import("jspdf-autotable"),
  ]);
  const f = data.format;
  const streams = data.streams ?? [];
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  doc.setFontSize(16);
  doc.text("ffScope — Analysis report", 40, 40);
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(path, 40, 56, { maxWidth: 515 });
  doc.setTextColor(0);

  autoTable(doc, {
    startY: 72,
    head: [["Summary", ""]],
    body: [
      ["File", basename(path)],
      ["Format", f?.format_long_name ?? f?.format_name ?? "-"],
      ["Duration", humanDuration(f?.duration)],
      ["Size", humanBytes(f?.size)],
      ["Total bitrate", humanBitrate(f?.bit_rate)],
      ["Streams", String(f?.nb_streams ?? streams.length)],
    ],
    styles: { fontSize: 8, cellPadding: 3 },
    headStyles: { fillColor: [47, 111, 237] },
    theme: "grid",
  });

  for (const s of streams) {
    autoTable(doc, {
      head: [[`#${s.index} ${s.codec_type ?? ""} — ${s.codec_name ?? ""}`, ""]],
      body: allFields(s),
      styles: { fontSize: 7, cellPadding: 2, overflow: "linebreak" },
      headStyles: { fillColor: [60, 66, 76] },
      columnStyles: { 0: { cellWidth: 150 } },
      theme: "grid",
    });
  }

  return new Uint8Array(doc.output("arraybuffer"));
}
